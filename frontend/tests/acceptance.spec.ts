import { test, expect } from "@playwright/test";
import path from "node:path";

test("new user uploads three PDFs, gets a cited answer, opens its page, saves a note, and deletes data", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await page.getByRole("button", { name: "New to ThesisAssistant? Create an account" }).click();
  await page.getByLabel("Email address").fill(`browser-${Date.now()}@example.org`);
  await page.getByLabel("Password", { exact: true }).fill("browser-acceptance-password");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await page.getByLabel("New project name").fill("Browser acceptance thesis");
  await page.getByRole("button", { name: "Create project", exact: true }).first().click();
  await page.locator('input[type="file"]').first().setInputFiles(["trial.pdf", "methods.pdf", "limitations.pdf"].map((name) => path.join(__dirname, "fixtures", name)));
  await expect(page.locator(".source-card")).toHaveCount(3);
  await expect(page.getByText("Indexed · Ready to cite", { exact: true })).toHaveCount(3);
  await page.locator("textarea").fill("By how many minutes did mean nightly sleep duration increase in the trial?");
  await page.getByRole("button", { name: "Send question" }).click();
  await expect(page.locator(".message.assistant").last()).toContainText("38");
  const citation = page.getByRole("button", { name: /trial.pdf.*p. 2/ }).first();
  await expect(citation).toBeVisible();
  await citation.click();
  await expect(page.getByRole("dialog", { name: "Source preview" })).toBeVisible();
  await expect(page.locator('iframe[title="Cited PDF page"]')).toBeVisible();
  await expect(page.locator('iframe[title="Cited PDF page"]')).toHaveAttribute("src", /#page=2$/);
  await page.getByText("Extracted source text", { exact: true }).click();
  await expect(page.getByRole("dialog").locator("pre")).toContainText("38 minutes");
  await page.getByRole("button", { name: "Close source preview" }).click();
  await page.getByRole("button", { name: "Save answer as a note" }).first().click();
  await expect(page.locator(".note-card")).toHaveCount(1);
  await page.locator("textarea").fill("What was the exact funding amount in US dollars for this trial?");
  await page.getByRole("button", { name: "Send question" }).click();
  await expect(page.locator(".message.assistant").last()).toHaveText(/I can't find this in your documents\./);
  await page.reload();
  await expect(page.locator(".message.assistant")).toHaveCount(2);
  await expect(page.locator(".note-card")).toHaveCount(1);
  await page.screenshot({ path: "test-results/verified-workspace.png", fullPage: true });
  await page.locator(".source-card").filter({ hasText: "methods.pdf" }).getByTitle("Summarize document").click();
  await expect(page.locator(".message.assistant").last()).toContainText("Method:");
  await expect(page.locator(".message.assistant").last()).toContainText("methods.pdf");
  await expect(page.getByTitle("Summarize document").first()).toBeEnabled();
  page.on("dialog", (dialog) => dialog.accept());
  await page.getByTitle("Delete source", { exact: true }).first().click();
  await expect(page.locator(".source-card")).toHaveCount(2);
  await page.getByTitle("Delete project", { exact: true }).click();
  await expect(page.locator(".project-row")).toHaveCount(0);
  expect(errors).toEqual([]);
});
